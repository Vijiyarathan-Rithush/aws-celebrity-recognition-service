#!/bin/bash
# Author: Vijiyarathan Rithush
# Desc:   Runs multiple tests and writes a fresh protocols.md with summary table.

set -u

cd "$(dirname "${BASH_SOURCE[0]}")"

LOG_FILE="docs/protocols.md"
TMP_DETAILS="$(mktemp)"

# Commands – NO_COLOR=1 verhindert ANSI-Codes im Log, falls mal umgeleitet wird
INSTALL_CMD="NO_COLOR=1 ./install.sh"
TEST_SINGLE_CMD="NO_COLOR=1 ./scripts/test_single.sh"
TEST_FLOW_CMD="NO_COLOR=1 ./scripts/test_flow.sh"

# Arrays für Summary-Tabelle
TEST_IDS=()
TEST_DESCS=()
TEST_EXPECTED=()
TEST_EXIT_CODES=()
TEST_ACTUAL=()
TEST_RESULTS=()

# usage: log_test TEST_ID DESC EXPECT_ERROR CMD...
# EXPECT_ERROR = 0 → success erwartet (exit 0)
# EXPECT_ERROR = 1 → Fehler erwartet (exit != 0)
log_test() {
  local TEST_ID="$1"
  local DESC="$2"
  local EXPECT_ERROR="$3"
  shift 3
  local CMD="$*"

  local DATE
  DATE="$(date '+%Y-%m-%d %H:%M:%S')"
  local USER_NAME="${USER:-unknown}"

  echo "=================================================="
  echo "Running test $TEST_ID: $DESC"
  echo "Command: $CMD"
  echo

  # Command ausführen – Ausgabe komplett unterdrücken, nur Exit-Code auswerten
  if eval "$CMD" >/dev/null 2>&1; then
    EXIT_CODE=0
  else
    EXIT_CODE=$?
  fi

  local EXPECTED_STR ACTUAL_STR RESULT

  if [[ "$EXPECT_ERROR" -eq 0 ]]; then
    EXPECTED_STR="success (exit 0)"
    if [[ "$EXIT_CODE" -eq 0 ]]; then
      ACTUAL_STR="success"
      RESULT="Pass"
    else
      ACTUAL_STR="error"
      RESULT="Fail"
    fi
  else
    EXPECTED_STR="error (exit != 0)"
    if [[ "$EXIT_CODE" -ne 0 ]]; then
      ACTUAL_STR="error"
      RESULT="Pass"
    else
      ACTUAL_STR="success"
      RESULT="Fail"
    fi
  fi

  # In Arrays für Summary speichern
  TEST_IDS+=("$TEST_ID")
  TEST_DESCS+=("$DESC")
  TEST_EXPECTED+=("$EXPECTED_STR")
  TEST_EXIT_CODES+=("$EXIT_CODE")
  TEST_ACTUAL+=("$ACTUAL_STR")
  TEST_RESULTS+=("$RESULT")

  # Kurz-Details für diesen Test ins Temp-File
  {
    echo
    echo "---"
    echo
    echo "### $TEST_ID – $DESC"
    echo
    echo "- **Date:** $DATE"
    echo "- **Tester:** $USER_NAME"
    echo "- **Command:** \`$CMD\`"
    echo "- **Expected:** $EXPECTED_STR"
    echo "- **Actual exit code:** $EXIT_CODE ($ACTUAL_STR)"
    echo "- **Result:** $RESULT"
    echo
  } >> "$TMP_DETAILS"

  echo "Result: $RESULT (exit code $EXIT_CODE)"
  echo
}

write_final_report() {
  mkdir -p "$(dirname "$LOG_FILE")"

  # protocols.md komplett überschreiben
  {
    echo "# Test Protocol – Face Recognition Project"
    echo
    echo "This file is generated by \`run_tests.sh\`."
    echo "Manual notes and screenshots can be added below each test."
    echo
    echo "## Summary"
    echo
    echo "| ID  | Description | Expected              | Exit code (actual) | Result |"
    echo "|-----|-------------|----------------------|---------------------|--------|"
    local i
    for i in "${!TEST_IDS[@]}"; do
      echo "| ${TEST_IDS[$i]} | ${TEST_DESCS[$i]} | ${TEST_EXPECTED[$i]} | ${TEST_EXIT_CODES[$i]} (${TEST_ACTUAL[$i]}) | ${TEST_RESULTS[$i]} |"
    done
    echo
    echo "## Details"
  } > "$LOG_FILE"

  # Detail-Blöcke anhängen
  cat "$TMP_DETAILS" >> "$LOG_FILE"
  rm -f "$TMP_DETAILS"
}

# ----------------- Tests definieren -----------------------

# T01: Clean Install
log_test "T01" "Clean install (deploy buckets, Lambda, role, trigger)" 0 "$INSTALL_CMD"

# T02: Re-Run Install (idempotent)
log_test "T02" "Re-run install.sh (idempotent deployment)" 0 "$INSTALL_CMD"

# T03: Single Image Test
log_test "T03" "Single image test (img/test1.jpg via test_single.sh)" 0 "$TEST_SINGLE_CMD"

# T04: Multi Image Test
log_test "T04" "Multi image test (all images in img/ via test_flow.sh)" 0 "$TEST_FLOW_CMD"

# T05: Kein Bild im Ordner – Fehler erwartet
run_t05_no_images() {
  local IMG_DIR="img"
  local BACKUP_DIR="img_backup_T05_$(date +%s)"

  if [[ -d "$IMG_DIR" ]]; then
    mv "$IMG_DIR" "$BACKUP_DIR"
  fi
  mkdir -p "$IMG_DIR"

  log_test "T05" "No images in img/ (expect clear error)" 1 "$TEST_FLOW_CMD"

  rm -rf "$IMG_DIR"
  if [[ -d "$BACKUP_DIR" ]]; then
    mv "$BACKUP_DIR" "$IMG_DIR"
  fi
}

run_t05_no_images

# T06: Falscher Bucket in config.env – Fehler erwartet
run_t06_wrong_bucket() {
  local CONFIG_ENV="config.env"
  local BACKUP="config.env.bak_T06_$(date +%s)"
  local WRONG_BUCKET="this-bucket-should-not-exist-123456"

  if [[ -f "$CONFIG_ENV" ]]; then
    cp "$CONFIG_ENV" "$BACKUP"
  fi

  if [[ -f "$CONFIG_ENV" ]]; then
    if grep -q '^IN_BUCKET_NAME=' "$CONFIG_ENV"; then
      sed -E "s|^IN_BUCKET_NAME=.*|IN_BUCKET_NAME=\"$WRONG_BUCKET\"|" "$CONFIG_ENV" > "${CONFIG_ENV}.tmp"
      mv "${CONFIG_ENV}.tmp" "$CONFIG_ENV"
    else
      echo "IN_BUCKET_NAME=\"$WRONG_BUCKET\"" >> "$CONFIG_ENV"
    fi
  else
    cat > "$CONFIG_ENV" <<EOF
IN_BUCKET_NAME="$WRONG_BUCKET"
EOF
  fi

  log_test "T06" "Wrong IN_BUCKET_NAME in config.env (expect clear error)" 1 "$TEST_FLOW_CMD"

  if [[ -f "$BACKUP" ]]; then
    mv "$BACKUP" "$CONFIG_ENV"
  else
    rm -f "$CONFIG_ENV"
  fi
}

run_t06_wrong_bucket

# Am Ende: Report schreiben
write_final_report
